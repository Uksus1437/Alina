'''
В файле содержится последовательность натуральных чисел, каждое из которых не превышает 100 000. 
Определите количество троек элементов последовательности, в которых не больше двух из трёх элементов чётные, 
а сумма элементов тройки не больше третьего по величине элемента последовательности.

В ответе запишите количество найденных троек чисел, затем максимальную из сумм элементов таких троек.

В данной задаче под тройкой подразумевается три идущих подряд элемента последовательности.


[3, 324, 1]
'''

f = open ("17.txt").readlines()
a = [int(x) for x in f]
res = []
mn = sorted([x for x in a])[-3]  # Третий по величине элемент последовательности

for i in range (len(a)-2):
  x1 = a[i]
  x2 = a[i+1]
  x3 = a[i+2]
  if ((99 < abs(x1) < 1000) +  (99 < abs(x2) < 1000) + (99 < abs(x3) < 1000)) == 2:
    if (x1 +x2 +x3) <= mn:
      res.append (x1+x2+x3)
print (len(res), max(res))
