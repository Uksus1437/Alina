'''
Значение арифметического выражения

9*11**210 + 8*11**150 - x,

где x  — целое положительное число, не превышающее 3000, записали в 11-ричной системе счисления. 
Определите наибольшее значение x, при котором в 11-ричной записи числа, 
являющегося значением данного арифметического выражения, содержится ровно 60 нулей.

В ответе запишите число в десятичной системе счисления.


Все пятибуквенные слова, составленные из букв А, К, Ц, Е, Н, Т, записаны в алфавитном
порядке и пронумерованы. Вот начало списка:
1. AAAAA
2. AAAAE
3. ААААК
4. ААААН
5. AAAAТ
6. ААААЦ
...
Определите, под каким номером в этом списке стоит первое слово, которое не начинается
с букв А, Е и К и при этом содержит в своей записи не менее одной буквы Т.
Примечание. Слово – последовательность идущих подряд букв, не обязательно осмысленная.
'''


def find_first_word():
    c = 0
    for x1 in "АЕКНТЦ":
        for x2 in "АЕКНТЦ":
            for x3 in "АЕКНТЦ":
                for x4 in "АЕКНТЦ":
                    for x5 in "АЕКНТЦ":
                        w = x1 + x2 + x3 + x4 + x5
                        c += 1
                        if (x1 != "А" and x1 != "Е" and x1 != "К") and w.count("Т") >= 1:
                            return c, w
    return None, None

c, w = find_first_word()
if c:
    print(c, w)  # expected: 3893 НАААТ

# Compute base-11 zeros case
for x in range(1, 3001):
    m = []
    y = 9*11**210 + 8*11**150 - x
    while y != 0:
        m.append(y % 11)
        y = y // 11
    if m.count(0) == 60:
        print(x)

