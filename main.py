'''
У исполнителя Калькулятор имеются три команды, которым присвоены номера:

1. Вычесть 1
2. Вычесть 3
3. Найти целую часть от деления на 2

Выполняя первую из них, исполнитель уменьшает число на экране на 1, выполняя вторую  — уменьшает на 3, 
выполняя третью  — делит на 2 нацело, отбрасывая остаток.
Сколько существует программ, для которых при исходном числе 31 результатом является число 3, и при этом траектория вычислений не содержит числа 20?
'''

def f(n,k):
  if n<k or n ==20:
    return 0
  if n == k:
    return 1
  if n > k:
    return f(n-1,k)+ f(n-3,k) + f (n//2,k)
print (f(31,3))


